/// Sort options for Cabs
enum CabSortOption {
  regNumberAZ, // Registration Number A-Z
  regNumberZA, // Registration Number Z-A
  routeAZ, // Route Name A-Z
  routeZA, // Route Name Z-A
  capacityAsc, // Capacity 0-9
  capacityDesc, // Capacity 9-0
  kmAsc, // Kilometers 0-9
  kmDesc, // Kilometers 9-0
}
